# Was ist das "3" und das "5"? = Literalen
# Was ist das "=" und "+"? = Operatoren

# Arithmetische Operatoren:
a = 5 + 1       # Addition
b = 3 - 1       # Subtraktion
c = 2 * 2       # Multiplikation
d = 4 / 2       # Division
e = 4 // 2      # Ganzzahldivision
f = 6 % 2       # Modulo
g = 10 ** 2     # Potenz

# Zuweisungsoperatoren
a = 5       # Einfache Zuweisung
a += 1      # Hinzufügen und Zuweisen
a -= 1      # Subtrahieren und Zuweisen
a *= 2      # Multiplizieren und Zuweisen
a /= 2      # Division und Zuweisen

# Vergleichsoperatoren
a == 1      # Gleich mit
a != 1      # Ungleich mit
a > 5       # Größer als
a < 5       # Kleiner als
a >= 5      # Größer Gleich als
a <= 5      # Kleiner Gleich als

# Logische Operatoren
b1 = True
b2 = False

a1 = b1 or b2
a2 = b1 and b2
a3 = not b1

